using System.Drawing;
using System.Drawing.Imaging;
using System.Reflection;
using System.Runtime.InteropServices;
using System.Runtime.Versioning;
using System.Windows.Forms;
using Personicore.DeviceAgent.Agent;
using Personicore.DeviceAgent.Config;

namespace Personicore.DeviceAgent.Ui;

/// <summary>
/// The notification-area icon is the Personicore mark tinted with the status colour:
/// green registered, orange owner missing, grey no node, red error. The state is read
/// from the colour; the shape is always the mark, so it stays recognisable
/// entre veinte iconos de bandeja.
///
/// The silhouettes come from `Resources/mark-NN.png`, generated by `build/make-icon.py`
/// from the logo's geometry. There is one per size because the mark is simplified
/// optically: at 16 px it draws 9 dots, not the original 25 — rescaling a single PNG
/// would turn the outer rings into dirt.
/// </summary>
[SupportedOSPlatform("windows")]
public static class TrayIcons
{
    [DllImport("user32.dll", SetLastError = true)]
    [return: MarshalAs(UnmanagedType.Bool)]
    private static extern bool DestroyIcon(IntPtr handle);

    /// <summary>Sizes with a silhouette of their own; must match TRAY_SIZES in the generator.</summary>
    private static readonly int[] Available = [16, 20, 24, 32, 40, 48, 64];

    private const string ResourcePrefix = "Personicore.DeviceAgent.Resources.mark-";

    private static readonly Dictionary<(AgentStatus, int), Icon> Cache = [];

    /// <summary>Icon for the tray, at the system's small-icon size (DPI aware).</summary>
    public static Icon For(AgentStatus status) => For(status, SystemInformation.SmallIconSize.Width);

    /// <summary>Icon for a window's title bar.</summary>
    public static Icon ForWindow(AgentStatus status) => For(status, 32);

    public static Icon For(AgentStatus status, int requestedSize)
    {
        var size = NearestAvailable(requestedSize);

        lock (Cache)
        {
            if (Cache.TryGetValue((status, size), out var cached)) return cached;

            var icon = Build(status, size);
            Cache[(status, size)] = icon;
            return icon;
        }
    }

    public static Color ColorFor(AgentStatus status) => status switch
    {
        AgentStatus.Registered => Palette.Good,
        AgentStatus.Simulated => Palette.Info,
        AgentStatus.OwnerRequired => Palette.Signal,
        // Waiting on Personicore support, not on the panelist: worth noticing, not alarming.
        AgentStatus.HouseholdNotAssigned or AgentStatus.BackendNotReady => Palette.Signal,
        AgentStatus.Error => Palette.Bad,
        AgentStatus.RouterNotFound => Palette.Idle,
        _ => Palette.Info,
    };

    private static int NearestAvailable(int requested)
    {
        var best = Available[0];
        foreach (var candidate in Available)
            if (Math.Abs(candidate - requested) < Math.Abs(best - requested)) best = candidate;

        return best;
    }

    private static Icon Build(AgentStatus status, int size)
    {
        using var silhouette = LoadSilhouette(size);
        using var tinted = Tint(silhouette, ColorFor(status));

        var handle = tinted.GetHicon();
        try
        {
            // Icon.FromHandle does not take ownership of the handle: it must be cloned
            // before destroying it, or the icon points at freed memory.
            using var borrowed = Icon.FromHandle(handle);
            return (Icon)borrowed.Clone();
        }
        finally
        {
            DestroyIcon(handle);
        }
    }

    private static Bitmap LoadSilhouette(int size)
    {
        var name = $"{ResourcePrefix}{size}.png";
        using var stream = Assembly.GetExecutingAssembly().GetManifestResourceStream(name);

        if (stream is not null) return new Bitmap(stream);

        // Should not happen: it means the .csproj and make-icon.py went out of sync.
        Log.Error($"Embedded resource {name} is missing; drawing a fallback dot.");
        return FallbackDot(size);
    }

    /// <summary>
    /// Replaces each pixel's colour while keeping its alpha. Done on the buffer rather
    /// than with DrawImage, so it does not depend on how GDI+ premultiplies when compositing.
    /// </summary>
    private static Bitmap Tint(Bitmap source, Color color)
    {
        var area = new Rectangle(0, 0, source.Width, source.Height);
        var result = new Bitmap(source.Width, source.Height, PixelFormat.Format32bppArgb);
        var pixels = new int[source.Width * source.Height];

        var read = source.LockBits(area, ImageLockMode.ReadOnly, PixelFormat.Format32bppArgb);
        try
        {
            Marshal.Copy(read.Scan0, pixels, 0, pixels.Length);
        }
        finally
        {
            source.UnlockBits(read);
        }

        var rgb = (color.R << 16) | (color.G << 8) | color.B;
        for (var i = 0; i < pixels.Length; i++)
        {
            var alpha = (pixels[i] >> 24) & 0xFF;
            pixels[i] = alpha == 0 ? 0 : (alpha << 24) | rgb;
        }

        var write = result.LockBits(area, ImageLockMode.WriteOnly, PixelFormat.Format32bppArgb);
        try
        {
            Marshal.Copy(pixels, 0, write.Scan0, pixels.Length);
        }
        finally
        {
            result.UnlockBits(write);
        }

        return result;
    }

    private static Bitmap FallbackDot(int size)
    {
        var bitmap = new Bitmap(size, size, PixelFormat.Format32bppArgb);
        using var g = Graphics.FromImage(bitmap);
        g.SmoothingMode = System.Drawing.Drawing2D.SmoothingMode.AntiAlias;
        using var brush = new SolidBrush(Color.White);
        g.FillEllipse(brush, size * 0.2f, size * 0.2f, size * 0.6f, size * 0.6f);
        return bitmap;
    }
}
